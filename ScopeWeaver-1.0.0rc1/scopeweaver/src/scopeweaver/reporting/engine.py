from scopeweaver.core.models import Assessment, StrictModel


def summary(report: Assessment) -> dict[str, Any]:
    services = {
        (s.host, s.ip, s.port, s.transport)
        for r in report.results
        for s in r.services
        if s.state == "open"
    }
    return {
        "findings": len(report.findings),
        "severity": report.statistics,
        "open_services": len(services),
        "module_results": len(report.results),
        "incomplete_results": sum(r.status != "completed" for r in report.results),
        "interrupted": report.interrupted,
        "assurance": "Observed configuration only; absence of findings is not proof of security.",
    }


class ReportDocument(StrictModel):
    schema_version: Literal["1.0"] = "1.0"
    assessment: Assessment
    summary: dict[str, Any]

    @model_validator(mode="after")
    def consistent_summary(self) -> ReportDocument:
        if self.summary != summary(self.assessment):
            raise ValueError("summary does not match assessment results")
        return self


def load_report(path: Path) -> Assessment:
    if path.stat().st_size > 50 * 1024 * 1024:
        raise ValueError("report exceeds 50 MiB")
    return ReportDocument.model_validate_json(path.read_text(encoding="utf-8")).assessment


def code_block(text: str) -> str:
    # A target-controlled banner must not close a Markdown evidence fence.
    longest = max((len(p) for p in re.findall(r"`+", text)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}\n{text}\n{fence}"


def md(text: str) -> str:
    value = html.escape(text, quote=False).replace("\n", " ").replace("\r", " ")
    for char in "\\`*_{}[]()#|!":
        value = value.replace(char, "\\" + char)
    return value


def markdown_report(report: Assessment) -> str:
    stats = summary(report)
    lines = [
        "# ScopeWeaver security assessment",
        "",
        "## Executive Summary",
        "",
        f"Run: {md(report.run_id)} · Version: {md(report.version)}",
        "",
        f"Findings: **{stats['findings']}** · Open services: **{stats['open_services']}** · "
        f"Incomplete module results: **{stats['incomplete_results']}**",
        "",
        f"Interrupted: **{report.interrupted}** · Network operations: **{report.network_operations}**",
        "",
        stats["assurance"],
        "",
        "| Severity | Count |",
        "| --- | ---: |",
    ]
    lines.extend(f"| {severity} | {count} |" for severity, count in report.statistics.items())
    lines.extend(
        [
            "",
            "## Scope",
            "",
            code_block(json.dumps(report.scope, indent=2)),
            "",
            "## Service Inventory",
            "",
            "| Host | IP | Port | State | Service | Detection |",
            "| --- | --- | ---: | --- | --- | --- |",
        ]
    )
    seen: set[tuple[str, str, int, str]] = set()
    for result in report.results:
        for service in result.services:
            key = (service.host, service.ip, service.port, service.state)
            if key in seen:
                continue
            seen.add(key)
            lines.append(
                f"| {md(service.host)} | {md(service.ip)} | {service.port} | "
                f"{md(service.state)} | {md(service.name)} | {md(service.detection)} |"
            )
    lines.extend(["", "## Findings", ""])
    if not report.findings:
        lines.append("No findings were generated by the completed checks.")
    for f in report.findings:
        lines.extend(
            [
                f"### {md(f.title)}",
                "",
                f"**{f.severity.value}** · {f.id} · {md(f.target)}",
                "",
                md(f.description),
                "",
                "**Technical Evidence**",
                "",
                code_block(json.dumps(f.evidence, indent=2, ensure_ascii=True)),
                "",
                "**Remediation**: " + md(f.remediation),
                "",
                "**CWE**: " + ", ".join(md(v) for v in f.cwe),
                "",
                "**CVSS**: "
                + (str(f.cvss) if f.cvss is not None else "Not assigned; context required"),
                "",
                "**References**: " + " · ".join(md(v) for v in f.references),
                "",
            ]
        )
    lines.extend(["", "## Module Evidence and Limitations", ""])
    for result in report.results:
        lines.extend(
            [
                f"### {md(result.module)} · {md(result.target)} · {md(result.status)}",
                "",
                code_block(
                    json.dumps(
                        {"observations": result.observations, "errors": result.errors},
                        indent=2,
                        ensure_ascii=True,
                    )
                ),
                "",
            ]
        )
    return "\n".join(lines) + "\n"


