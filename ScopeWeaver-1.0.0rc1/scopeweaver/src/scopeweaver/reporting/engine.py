def html_report(report: Assessment) -> str:
    env = Environment(autoescape=True)
    services = {(s.host, s.ip, s.port, s.state): s for r in report.results for s in r.services}
    return env.from_string(TEMPLATE).render(
        report=report,
        stats=summary(report),
        services=list(services.values()),
        scope_json=json.dumps(report.scope, indent=2),
        evidence={
            f.id: json.dumps(f.evidence, indent=2, ensure_ascii=True) for f in report.findings
        },
        observations=[
            json.dumps(r.observations, indent=2, ensure_ascii=True) for r in report.results
        ],
        safe_url=lambda value: urlsplit(value).scheme in {"http", "https"},
    )


def write_reports(
    report: Assessment,
    directory: Path,
    formats: list[str] | None = None,
    *,
    overwrite: bool = False,
) -> list[Path]:
    selected = list(dict.fromkeys(formats or ["json", "md", "html"]))
    if not set(selected) <= {"json", "md", "html"}:
        raise ValueError("formats must be json, md or html")
    directory.mkdir(parents=True, exist_ok=True)
    paths = [directory / f"assessment.{fmt}" for fmt in selected]
    if not overwrite and any(path.exists() for path in paths):
        raise FileExistsError("report already exists; use a new output directory or --overwrite")
    document = ReportDocument(assessment=report, summary=summary(report))
    content = {
        "json": lambda: document.model_dump_json(indent=2),
        "md": lambda: markdown_report(report),
        "html": lambda: html_report(report),
    }
    for fmt, path in zip(selected, paths, strict=True):
        fd, temporary = tempfile.mkstemp(prefix=".scopeweaver-", dir=directory)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(content[fmt]())
                stream.flush()
                os.fsync(stream.fileno())
            if overwrite:
                os.replace(temporary, path)
            else:
                # Hard link gives no-clobber semantics even if another process races the preflight.
                os.link(temporary, path)
        finally:
            Path(temporary).unlink(missing_ok=True)
    return paths
